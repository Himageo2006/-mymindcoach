/** Returns native-language coaches first, then all other coaches (who respond in English) */
export function getCoachesForLanguage(lang) {
  const nativeLang = COACHES[lang] ? lang : 'en';
  const native = (COACHES[nativeLang] || []).map(c => ({ ...c, isNative: true }));

  // All other language groups — respond in English regardless of their own language
  const others = Object.entries(COACHES)
    .filter(([l]) => l !== nativeLang)
    .flatMap(([, coaches]) =>
      coaches.map(c => ({
        ...c,
        language: 'en',        // these coaches speak English to this user
        isNative: false,
      }))
    );

  return [...native, ...others];
}

/** Returns only the coaches for a specific language (used internally) */
export function getNativeCoaches(lang) {
  return COACHES[lang] || COACHES['en'];
}
